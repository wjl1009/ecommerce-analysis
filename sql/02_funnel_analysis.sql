-- ════════════════════════════════════════════════════════
-- 漏斗分析与归因
-- ════════════════════════════════════════════════════════
-- 目的：看用户在购买流程的哪一步流失最多，并定位"销售额下降是谁的锅"
-- 原理：5步漏斗（下单→有商品→支付→交付→好评），逐月跟踪转化率
--       用 LAG() 窗口函数做环比，发现哪个环节在恶化
-- 输出：每月的漏斗数据 + 转化率 + 环比变化 + 预警
-- ════════════════════════════════════════════════════════

WITH
-- ████████████████████████████████████████████████████████
-- 步骤1：按月统计每个步骤经过了几个用户
-- ████████████████████████████████████████████████████████
-- 关键技巧：COUNT(DISTINCT CASE WHEN 条件 THEN 用户 END)
--         = 只数"满足条件"的用户，不满足的不计数
-- LEFT JOIN 的作用：连不上评论表也不会丢掉整行（有的订单没评论）
-- ████████████████████████████████████████████████████████
按月统计各步人数 AS (
    SELECT
        strftime('%Y-%m', o.order_purchase_timestamp) AS 月份,

        -- 第1步：只要下过单就算
        COUNT(DISTINCT o.customer_id)                 AS 下单用户数,

        -- 第2步：下单且订单里有商品（order_items 表有记录）
        COUNT(DISTINCT CASE WHEN oi.order_item_id IS NOT NULL
            THEN o.customer_id END)                    AS 有商品用户数,

        -- 第3步：下过单且有支付记录
        COUNT(DISTINCT CASE WHEN op.payment_type IS NOT NULL
            THEN o.customer_id END)                    AS 已支付用户数,

        -- 第4步：订单状态是 delivered（已交付）
        COUNT(DISTINCT CASE WHEN o.order_status = 'delivered'
            THEN o.customer_id END)                    AS 已交付用户数,

        -- 第5步：已交付且评分 >= 4（好评）
        COUNT(DISTINCT CASE WHEN o.order_status = 'delivered'
            AND orv.review_score >= 4
            THEN o.customer_id END)                    AS 好评用户数

    FROM orders o
    LEFT JOIN order_items    oi  ON o.order_id = oi.order_id
    LEFT JOIN order_payments op  ON o.order_id = op.order_id
    LEFT JOIN order_reviews  orv ON o.order_id = orv.order_id
    WHERE o.order_purchase_timestamp >= '2017-01-01'
    GROUP BY 月份
),

-- ████████████████████████████████████████████████████████
-- 步骤2：计算每一步的转化率
-- ████████████████████████████████████████████████████████
-- 步转化率 = 本步人数 / 上一步人数 × 100
-- 比如：商品到支付 = 已支付 / 有商品
-- NULLIF(分母, 0) 防止除以0报错，分母为0时返回 NULL
-- ████████████████████████████████████████████████████████
计算转化率 AS (
    SELECT
        月份,
        下单用户数,
        有商品用户数,
        已支付用户数,
        已交付用户数,
        好评用户数,

        -- 每一步相对于前一步的转化率
        -- 如果下单用户数=0，NULLIF会返回NULL而不是0
        ROUND(100.0 * 有商品用户数 / NULLIF(下单用户数, 0), 1) AS 下单到商品转化率,
        ROUND(100.0 * 已支付用户数 / NULLIF(有商品用户数, 0), 1) AS 商品到支付转化率,
        ROUND(100.0 * 已交付用户数 / NULLIF(已支付用户数, 0), 1) AS 支付到交付转化率,
        ROUND(100.0 * 好评用户数   / NULLIF(已交付用户数, 0), 1) AS 交付到好评转化率

    FROM 按月统计各步人数
),

-- ████████████████████████████████████████████████████████
-- 步骤3：和上个月比，看变化
-- ████████████████████████████████████████████████████████
-- LAG(列名) OVER (ORDER BY 月份) = 取出上一行的值
-- 例：本月下单1000，上月下单900 → 环比 = (1000-900)/900 = +11.1%
-- ████████████████████████████████████████████████████████
环比分析 AS (
    SELECT
        *,
        -- 上个月下单量
        LAG(下单用户数) OVER (ORDER BY 月份) AS 上月下单量,
        -- 下单量环比变化（%）
        ROUND(
            100.0 * (下单用户数 - LAG(下单用户数) OVER (ORDER BY 月份))
            / NULLIF(LAG(下单用户数) OVER (ORDER BY 月份), 0),
            1
        ) AS 下单环比变化
    FROM 计算转化率
)

-- ████████████████████████████████████████████████████████
-- 步骤4：输出 + 自动预警
-- ████████████████████████████████████████████████████████
-- 预警逻辑（按优先级排查）：
--   1. 支付转化率比上月掉了超过 2 个百分点？ → 支付环节出问题
--   2. 下单到商品转化率掉了超过 2 个百分点？  → 浏览/选择环节出问题
--   3. 下单量本身掉了超过 10%？               → 流量出问题
--   4. 都没有 → 正常
-- ████████████████████████████████████████████████████████
SELECT
    月份,
    下单用户数,
    有商品用户数,
    已支付用户数,
    已交付用户数,
    好评用户数,
    下单到商品转化率,
    商品到支付转化率,
    支付到交付转化率,
    交付到好评转化率,
    下单环比变化,
    CASE
        -- 优先级1：支付环节转化率下降（最影响收入）
        WHEN 商品到支付转化率 < LAG(商品到支付转化率) OVER (ORDER BY 月份) - 2
            THEN '[!] 支付环节转化率下降'
        -- 优先级2：下单环节转化率下降
        WHEN 下单到商品转化率 < LAG(下单到商品转化率) OVER (ORDER BY 月份) - 2
            THEN '[!] 下单环节转化率下降'
        -- 优先级3：流量/下单量下降
        WHEN 下单环比变化 < -10
            THEN '[!] 下单量下滑超过10%'
        ELSE '正常'
    END AS 预警
FROM 环比分析
WHERE 月份 >= '2017-04-01'   -- 给 LAG 留足数据（前3个月作为基准）
ORDER BY 月份;




--   - 下单→支付转化率低（最常见的问题）→ 测试支付页简化流程、加信任标识、加支付方式
--   - 支付→交付转化率低 → 排查物流商、优化发货时效
--   - 交付→好评转化率低 → 商品质量问题，需要品控部门介入
--   - 下单量本身下滑 → 需要市场部看流量来源是不是出了问题