-- ════════════════════════════════════════════════════════
-- 卖家同期群留存分析
-- ════════════════════════════════════════════════════════
-- 目的：看每个批次入驻的卖家，有多少人在后续月份继续卖货
-- 原理：
--   ① 找到每个卖家的"首次卖货月份"（同期群标签）
--   ② 找到每个卖家"所有卖货的月份"
--   ③ 把①②按卖家ID关联，算出"第N月还剩多少人"
-- 数据说明：Olist 客户无复购，改用卖家维度做留存
-- ════════════════════════════════════════════════════════  把 3000+ 个卖家按"首次卖货月份"分成批次，追踪每个批次在后续月份还有多少人在卖货

WITH
-- ████████████████████████████████████████████████████████
-- 步骤1：每个卖家第一次卖货的月份 = 他属于哪个"同期群"
-- ████████████████████████████████████████████████████████
-- MIN(时间) = 取最早的订单时间
-- strftime('%Y-%m', 时间) = 把时间戳转成"年-月"格式，如 2017-03
-- 结果示例：卖家A → 2017-03, 卖家B → 2017-06
-- ████████████████████████████████████████████████████████

--     每个卖家属于哪个批次

卖家首次卖货月份 AS (
    SELECT
        s.seller_id                                          AS 卖家ID,
        strftime('%Y-%m', MIN(o.order_purchase_timestamp))   AS 同期群月份
    FROM sellers        s
    JOIN order_items    oi ON s.seller_id  = oi.seller_id
    JOIN orders         o  ON oi.order_id  = o.order_id
    WHERE o.order_status = 'delivered'
    GROUP BY s.seller_id
),

-- "同期群"就是"同一批次"——同一个月开始卖货的卖家，被归为一组

-- ████████████████████████████████████████████████████████
-- 步骤2：每个卖家所有卖过货的月份
-- ████████████████████████████████████████████████████████
-- DISTINCT：同一个月卖多单只算一次（我们关心"这个月在不在"，不关心"卖了几单"）
-- 结果示例：卖家A → 2017-03, 2017-05, 2017-08（三个月份各一条）
-- ████████████████████████████████████████████████████████

--     每个卖家在哪几个月卖过货

卖家所有活跃月份 AS (
    SELECT DISTINCT
        s.seller_id                                          AS 卖家ID,
        strftime('%Y-%m', o.order_purchase_timestamp)        AS 活跃月份
    FROM sellers        s
    JOIN order_items    oi ON s.seller_id  = oi.seller_id
    JOIN orders         o  ON oi.order_id  = o.order_id
    WHERE o.order_status = 'delivered'
),

-- ████████████████████████████████████████████████████████
-- 步骤3：把"首次月份"和"活跃月份"拼在一起，算间隔
-- ████████████████████████████████████████████████████████
-- 核心逻辑：
--   卖家A 首次=2017-03, 活跃月份有 2017-03, 2017-05, 2017-08
--   JOIN后变成三行：
--     2017-03 | 2017-03 | 第0月（首月）
--     2017-03 | 2017-05 | 第2月（过了2个月还在卖）
--     2017-03 | 2017-08 | 第5月（过了5个月还在卖）
--
-- 月份偏移公式：(年份差×12) + 月份差
--   例：(2017-2017)×12 + (5-3) = 2  → 第2月
-- ████████████████████████████████████████████████████████

--     把两个表 JOIN，算"这是第几个月"

留存矩阵 AS (
    SELECT
        a.同期群月份,
        b.活跃月份,
        -- 计算"这是第几个月"
        -- SUBSTR('2017-05', 1, 4) = '2017' → 转数字 = 2017
        -- SUBSTR('2017-05', 6, 2) = '05'   → 转数字 = 5
        (CAST(SUBSTR(b.活跃月份, 1, 4) AS INTEGER) - CAST(SUBSTR(a.同期群月份, 1, 4) AS INTEGER)) * 12
        + (CAST(SUBSTR(b.活跃月份, 6, 2) AS INTEGER) - CAST(SUBSTR(a.同期群月份, 6, 2) AS INTEGER))
        AS 第N月,
        COUNT(DISTINCT a.卖家ID) AS 留存卖家数
    FROM 卖家首次卖货月份   a
    JOIN 卖家所有活跃月份   b ON a.卖家ID = b.卖家ID
    WHERE b.活跃月份 >= a.同期群月份   -- 只看首月及之后的数据
    GROUP BY a.同期群月份, b.活跃月份
),

-- ████████████████████████████████████████████████████████
-- 步骤4：每个同期群总共有几个卖家（作为留存率的分母）
-- ████████████████████████████████████████████████████████

--     每个批次总共多少人（留存率的分母）

同期群规模 AS (
    SELECT
        同期群月份,
        COUNT(DISTINCT 卖家ID) AS 总卖家数
    FROM 卖家首次卖货月份
    GROUP BY 同期群月份
)

-- ████████████████████████████████████████████████████████
-- 步骤5：输出留存率 + 预警
-- ████████████████████████████████████████████████████████
-- 留存率 = 第N月还在卖的人数 / 这个同期群总人数 × 100
-- 预警阈值：第1月低于50% 或 第3月低于30%（卖家留存比用户高，阈值也相应调高）
-- WHERE 总卖家数 >= 10：过滤样本太小的同期群（没参考价值）
-- ████████████████████████████████████████████████████████
SELECT
    m.同期群月份,
    s.总卖家数                                   AS 首月卖家数,
    m.第N月,
    m.留存卖家数,
    ROUND(100.0 * m.留存卖家数 / s.总卖家数, 1)   AS 留存率百分比,
    CASE
        WHEN m.第N月 = 1 AND 100.0 * m.留存卖家数 / s.总卖家数 < 50
            THEN '[!] 第1月卖家留存低于50%'
        WHEN m.第N月 = 3 AND 100.0 * m.留存卖家数 / s.总卖家数 < 30
            THEN '[!] 第3月卖家留存低于30%'
    END AS 预警
FROM 留存矩阵     m
JOIN 同期群规模   s ON m.同期群月份 = s.同期群月份
WHERE s.总卖家数 >= 10
ORDER BY m.同期群月份, m.第N月;




--   1. 第 1 月是黄金窗口期
--
--   第 1 月留存 55-71%，之后每个月衰减 5-10%。如果卖家第 1 个月活下来了，大概率会持续经营。所以平台应该在卖家入驻首月重点扶持——教程、流量倾斜、快速响应问题。
--
--   2. 2017-06 同期群异常
--
--   第 1 月留存仅 43%，远低于其他批次的 55-71%。值得排查：
--   - 是平台改了政策？
--   - 是那个月涌入了一批低质量卖家？
--   - 是季节性因素（巴西 6 月是冬季）？
--
--   3. 留存衰减是渐进式而非断崖式
--
--   曲线是平缓下降，不是突然垮掉。说明卖家不是"做一笔就跑"，而是有持续经营意愿——平台生态是健康的。


