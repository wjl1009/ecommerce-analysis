-- ════════════════════════════════════════════════════════
-- RFM 用户价值分群
-- ════════════════════════════════════════════════════════
-- 目的：把用户按消费行为分成不同价值等级
-- 原理：R(最近购买距今天数) + F(购买次数) + M(消费金额)
--       R越小越好、F越大越好、M越大越好
-- 输出：5 个用户群体，每群的人数、平均消费等画像指标
-- ════════════════════════════════════════════════════════

WITH
-- 步骤1：给每个用户算三个数（R、F、M）
-- ──────────────────────────────────────
-- julianday() 把日期转成数字（从公元前4714年起算的天数）
-- 两个日期相减 = 间隔天数，也就是"距今多少天没买了"
-- ──────────────────────────────────────
每个用户的RFM值 AS (
    SELECT
        c.customer_unique_id                                AS 用户ID,
--         用户最后一次下单离参考日期过了多少天。天数越小 = 越活跃
        julianday('2018-09-01') - julianday(MAX(o.order_purchase_timestamp)) AS 最近购买距今天数,
--         用户一共下过几单。越多越好
        COUNT(DISTINCT o.order_id)                          AS 购买次数,
--         用户总共花了多少钱。越多越好
        SUM(oi.price + oi.freight_value)                    AS 消费总额
    FROM customers      c
    JOIN orders         o  ON c.customer_id = o.customer_id
    JOIN order_items    oi ON o.order_id    = oi.order_id
    WHERE o.order_status = 'delivered'     -- 只看已交付的订单
    GROUP BY c.customer_unique_id
),

-- 步骤2：给每个 R/F/M 打 1~5 分
-- ──────────────────────────────────────
-- NTILE(5) 把全部用户按某个值排序后均匀切成 5 份
-- 第 1 份最好（分最低）、第 5 份最差（分最高）
-- R 越小越好 → ASC 升序（天数少的排前面，NTILE=1）
-- F 越大越好 → DESC 降序（次数多的排前面，NTILE=1）
-- M 越大越好 → DESC 降序（金额多的排前面，NTILE=1）
-- ──────────────────────────────────────
RFM打分 AS (
    SELECT
        用户ID,
        最近购买距今天数,
        购买次数,
        消费总额,
        NTILE(5) OVER (ORDER BY 最近购买距今天数 ASC)  AS R分,  -- 1=最近买过, 5=很久没买
        NTILE(5) OVER (ORDER BY 购买次数 DESC)         AS F分,  -- 1=买很多次, 5=买很少
        NTILE(5) OVER (ORDER BY 消费总额 DESC)         AS M分   -- 1=花很多钱, 5=花很少
    FROM 每个用户的RFM值
),

-- 步骤3：根据 R/F/M 分数，把人分到不同群体
-- ──────────────────────────────────────
-- 核心规则：
--   三个分数都小(≤2) = 好用户 → 高价值
--   R小但F和M大(≥4)        → 新用户（最近才来，买的还不多）
--   R大但F和M小            → 快流失了（很久没来但以前买得多）
--   三个都大                → 已经流失了
--   其他                    → 一般用户
-- ──────────────────────────────────────
用户分群 AS (
    SELECT
        *,
        R分 + F分 + M分 AS 综合得分,      -- 3分最好，15分最差
        CASE
            WHEN R分 <= 2 AND F分 <= 2 AND M分 <= 2                 THEN '高价值用户'
            WHEN R分 <= 2 AND F分 >= 4 AND M分 >= 4                 THEN '新用户'
            WHEN R分 >= 4 AND F分 <= 2 AND M分 <= 2                 THEN '流失风险用户'
            WHEN R分 >= 4 AND F分 >= 4 AND M分 >= 4                 THEN '已流失用户'
            ELSE '一般用户'
        END AS 用户群体
    FROM RFM打分
)

-- 步骤4：按群体汇总，看每个群体的画像
-- ──────────────────────────────────────
-- SUM(COUNT(*)) OVER() 是窗口函数，计算"当前行COUNT占全部COUNT的比例"
-- 等价于：当前群体人数 / 所有群体人数总和
-- ──────────────────────────────────────
SELECT
    用户群体,
    COUNT(*)                       AS 用户数,
    ROUND(AVG(最近购买距今天数), 1)  AS 平均距今天数,
    ROUND(AVG(购买次数), 1)         AS 平均购买次数,
    ROUND(AVG(消费总额), 2)         AS 人均消费,
    ROUND(SUM(消费总额), 2)         AS 群体总收入,
    ROUND(100.0 * COUNT(*) / SUM(COUNT(*)) OVER(), 1) AS 人数占比
FROM 用户分群
GROUP BY 用户群体
ORDER BY 群体总收入 DESC;




-- 5 个群体的运营策略
--
--   1. 高价值用户（16.5%，人均 R$296）
--
--   特征：最近买过、消费高、忠诚度高
--
--   策略 — 维护，不要打扰：
--   - VIP 体系：专属客服、优先发货、生日礼遇。不是发优惠券（他们本来就买，发券是浪费利润）
--   - 新品首发：上新时优先通知这批人，他们是种子用户
--   - 推荐引擎：基于购买记录做个性化推荐，提高连带率
--
--   衡量指标：复购率、客单价是否稳定。这批人如果 R 分开始变大（超过 30 天没买），立即触发人工触达。
--
--   ---
--   2. 流失风险用户（15.6%，人均 R$301）
--
--   特征：曾经花很多钱，但很久没来了——这是最有价值的一批人
--
--   策略 — 召回，不惜成本：
--   - push + 短信 + 邮件三通道触达："我们想你了，回来看看"
--   - 大额优惠券：R$30-50 无门槛券，ROI 算得过——这批人以前人均消费 R$301
--   - 限时活动：制造紧迫感，"仅限 3 天，老客专享 8 折"
--   - 人工回访：如果金额够高（Top 1%），可以考虑电话/WhatsApp 回访，问为什么不来了
--
--   衡量指标：召回率（触达后 7 天内是否下单）、召回 ROI（券成本 vs 回流消费）
--
--   ---
--   3. 新用户（15.4%，人均 R$53）
--
--   特征：刚来，消费还不高
--
--   策略 — 激活，推他一把：
--   - 首单后 24h 内发券："感谢首单，第二单立减 R$10"——趁热打铁
--   - 新手引导：推荐平台 bestseller，降低选择困难
--   - 品类拓展：他买了什么品类，推荐互补品类（买手机壳的推荐钢化膜）
--
--   衡量指标：7 天内二单率、30 天内二单率
--
--   ---
--   4. 一般用户（36.0%，人均 R$131）
--
--   特征：各方面都居中，最大的群体
--
--   策略 — 精细化运营，定向提频：
--   - 按品类偏好分组：买电子产品和买家居家纺的用户行为完全不同，分开运营
--   - 满减活动：R$150 减 R$20——略高于他们当前客单价（R$131），引导提高消费
--   - 签到/积分体系：提高访问频次，养成"没事逛逛"的习惯
--
--   衡量指标：客单价提升幅度、月活频次
--
--   ---
--   5. 已流失用户（16.5%，人均 R$55）
--
--   特征：很久没来，消费也低
--
--   策略 — 低成本试探，不行就放弃：
--   - EDM 批量触达：成本几乎为零，大规模推送
--   - 大促节点触达：黑五、双十一等，借势召回
--   - 不要再砸钱：这批人 ROI 大概率是负的，把预算留给"流失风险用户"
